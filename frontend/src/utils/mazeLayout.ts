/**
 * Expands a base grid to a target size by repeating cells.
 * Example: 25x25 base -> 100x100 (each cell becomes 4x4)
 */
export const expandGrid = (base: number[][], scale: number = 4): number[][] => {
  const height = base.length;
  const width = base[0].length;
  const expanded: number[][] = [];

  for (let y = 0; y < height * scale; y++) {
    expanded[y] = [];
    for (let x = 0; x < width * scale; x++) {
      expanded[y][x] = base[Math.floor(y / scale)][Math.floor(x / scale)];
    }
  }
  return expanded;
};

